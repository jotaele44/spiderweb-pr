def _epoch(provenance: bool) -> EpochRecord:
    return EpochRecord(
        record_id="r",
        epoch_id="e",
        capture_time="2020-01-01T00:00:00Z",
        provider="p",
        resolution_m=10.0,
        geometry_id="g",
        provenance={"scene_id": "s"} if provenance else {},
    )


def _observation(case: dict) -> TemporalObservation:
    inputs = case["inputs"]
    return TemporalObservation(
        comparison_id="golden",
        before=_epoch(inputs["before_provenance"]),
        after=_epoch(inputs["after_provenance"]),
        change_signals=case["signals"],
        spatial_overlap=inputs["spatial_overlap"],
        registration_quality=inputs["registration_quality"],
        scale_compatibility=inputs["scale_compatibility"],
        view_angle_compatibility=inputs["view_angle_compatibility"],
        artifact_confidence=inputs["artifact_confidence"],
        contradiction_confidence=inputs["contradiction_confidence"],
    )


@pytest.mark.parametrize("case", GOLDEN, ids=[c["label"] for c in GOLDEN])
def test_port_matches_the_original_numerically(case):
    score = sc.score_temporal_change(_observation(case))
    got = sc.score_summary(score)
    assert got == case["expected"]


def test_golden_table_covers_every_class():
    assert {c["expected"]["classification"] for c in GOLDEN} == {
        member.value for member in TemporalClass
    }


def test_golden_table_has_boundary_cases():
    labels = {c["label"] for c in GOLDEN}
    assert {"boundary alignment 0.6", "boundary confirmed 0.7"} <= labels


def test_unknown_change_keys_are_ignored():
    obs = observation_for_score({"MADE_UP_CLASS": 0.99, "EXPANSION": 0.5})
    assert sc.score_temporal_change(obs).change_types == ("EXPANSION",)


# --- resolution rule (chosen here, not part of the original) -------------------


def test_coarse_imagery_keeps_only_coarse_classes():
    signals = {item.value: 0.8 for item in ChangeType}
    kept, dropped = sc.restrict_to_resolution(signals, 10.0)
    assert set(kept) == set(sc.COARSE_CHANGE_TYPES)
    assert set(dropped) == {item.value for item in ChangeType} - set(
        sc.COARSE_CHANGE_TYPES
    )


def test_fine_imagery_keeps_everything():
    signals = {item.value: 0.8 for item in ChangeType}
    kept, dropped = sc.restrict_to_resolution(signals, 1.0)
    assert kept == signals and dropped == ()


def test_resolution_boundary_is_inclusive_of_five_metres():
    signals = {ChangeType.NEW_FEATURE.value: 0.8}
    assert sc.restrict_to_resolution(signals, sc.COARSE_ONLY_ABOVE_M)[0] == signals
    assert sc.restrict_to_resolution(signals, sc.COARSE_ONLY_ABOVE_M + 0.1)[0] == {}


def test_unknown_resolution_is_treated_as_coarse():
    signals = {ChangeType.NEW_FEATURE.value: 0.8}
    kept, dropped = sc.restrict_to_resolution(signals, None)
    assert kept == {} and dropped == (ChangeType.NEW_FEATURE.value,)
